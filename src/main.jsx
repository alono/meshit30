import { StrictMode, Suspense, lazy } from 'react';
import { createRoot } from 'react-dom/client';
import App from './App.jsx';
import './styles.css';

// The local content admin exists only on the dev server: this condition is a
// constant false in a production build, so the screen is never even bundled.
const Admin = import.meta.env.DEV && window.location.pathname.startsWith('/admin')
  ? lazy(() => import('./screens/Admin.jsx'))
  : null;

// A tab left open across a deploy still runs the old entry, whose content
// chunks the new deploy no longer has. Reload onto the new version instead of
// showing a load error — at most once a minute, so a chunk that is really
// broken shows the error rather than reloading forever.
window.addEventListener('vite:preloadError', (event) => {
  try {
    const last = Number(sessionStorage.getItem('meshit30:reloadedAt'));
    if (Date.now() - last < 60_000) return;
    sessionStorage.setItem('meshit30:reloadedAt', String(Date.now()));
  } catch {
    return;
  }
  event.preventDefault();
  window.location.reload();
});

createRoot(document.getElementById('root')).render(
  <StrictMode>
    {Admin ? <Suspense fallback={null}><Admin /></Suspense> : <App />}
  </StrictMode>,
);

// Offline support: dist/sw.js is generated by scripts/build-sw.mjs at build
// time with the full precache list, so it exists only in production builds.
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  window.addEventListener('load', () => {
    navigator.serviceWorker.register('/sw.js').catch(() => {
      // Offline is an enhancement; a failed registration must not break the app.
    });
  });
}
